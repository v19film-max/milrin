export function fill(tpl, vars = {}) {
  return String(tpl).replace(/\{([^}]+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
// "{이름}{아/야}" 자리: 한글이면 아/야, 아니면 이름~
export function nameCall(name) {
  const n = cleanText(name);
  const s = ahYa(n);
  return s === '~' ? `${n}~` : `${n}${s}`;
}
export function fillS(tpl, vars) {
  return fill(String(tpl).replace('{이름}{아/야}', '{호칭}'), { ...vars, 호칭: nameCall(vars.이름) });
}
export function whatText(merchants, cutTo = 12) {
  const list = [...new Set(merchants.map((m) => cleanText(m)).filter(Boolean).map((m) => clipText(m, cutTo)))];
  if (list.length === 0) return UI.thisItem;
  if (list.length === 1) return list[0];
  if (list.length === 2) return `${list[0]}이랑 ${list[1]}`;
  return `${list[0]} 외 ${list.length - 1}건`;
}
